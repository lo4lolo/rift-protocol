import test from 'node:test';
import assert from 'node:assert/strict';
import { PracticeSession } from '../practice.mjs';
test('Pages practice starts with nine bots, supports purchase, input and private snapshots',()=>{
  const messages=[];
  const s=new PracticeSession(m=>messages.push(m));
  s.receive({type:'join',name:'웹 플레이어',agent:'haven'});
  assert.equal(s.game.players.size,10);
  assert.equal(messages[0].type,'welcome');
  assert.equal(s.game.players.get(s.id).agent,'haven');
  s.receive({type:'start'});
  assert.equal(s.game.phase,'buy');
  s.receive({type:'buy',item:'lightArmor'});
  assert.equal(s.game.players.get(s.id).armor,25);
  s.receive({type:'ping',stamp:123});
  assert.deepEqual(messages.at(-1),{type:'pong',stamp:123});
  for(let i=0;i<1300;i++)s.tick(1/60);
  assert.equal(s.game.phase,'live');
  s.snapshot();
  const state=messages.at(-1).state;
  assert.equal(state.players.length,10);
  const player=s.game.players.get(s.id);
  s.receive({type:'input',seq:1,round:s.game.round,yaw:0,pitch:0,w:true,steps:2});
  s.tick(1/60);s.tick(1/60);
  assert.ok(player.seq>=1);
  s.receive({type:'chat',requestId:42,text:'준비 완료'});
  assert.equal(messages.at(-1).type,'chatAck');
  assert.equal(messages.at(-1).accepted,true);
  s.snapshot();
  const first=messages.at(-1).state.events;
  s.snapshot();
  assert.equal(messages.at(-1).state.events.length,0);
  assert.ok(first.length>0);
});
